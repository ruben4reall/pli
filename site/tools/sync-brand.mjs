// Brings Pli's brand into the site: the tokens and assets of brand/ (Plan 4) when present, the site's own otherwise.
// Usage: node tools/sync-brand.mjs [--from <repo root>]   (default: the repository holding this site)
// Writes css/tokens.css and assets/brand/*; prints where each one came from.
import { execFileSync } from 'node:child_process';
import { copyFile, mkdir, readFile, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';

export const SITE_DIR = resolve(fileURLToPath(new URL('..', import.meta.url)));
const FALLBACK = join(SITE_DIR, 'tools', 'brand-fallback');

/** Spec section 9.2 palette and Plan 4's motion tokens: the values the site uses when the brand has none. */
export const SITE_TOKENS = Object.freeze({
  '--pli-night': '#0A0C10',
  '--pli-slate': '#161A22',
  '--pli-ice': '#EEF2F6',
  '--pli-mist': '#8A94A3',
  '--pli-glacier': '#7CCBFF',
  '--pli-deep-glacier': '#0B6FB0',
  '--pli-iridescent-1': '#A6F0FF',
  '--pli-iridescent-2': '#C8B8FF',
  '--pli-iridescent-3': '#FFD3B0',
  '--pli-white': '#FFFFFF',
  '--pli-paper': '#F5F5F7',
  '--pli-ink': '#1D1D1F',
  '--pli-graphite': '#6E6E73',
  '--pli-hairline': '#D2D2D7',
  '--pli-ease-fold': 'cubic-bezier(0.65, 0, 0.35, 1)',
  '--pli-ease-reveal': 'cubic-bezier(0.33, 1, 0.68, 1)',
});

/** tokens.css: the site defaults first, then the brand's file, so the brand wins wherever both define a name. */
export function renderTokens(brandCss) {
  const defaults = Object.entries(SITE_TOKENS).map(([name, value]) => `  ${name}: ${value};`).join('\n');
  const brand = brandCss === null
    ? '/* brand/tokens/tokens.css was not found: the site defaults above apply. */\n'
    : `/* From brand/tokens/tokens.css: */\n${brandCss.trim()}\n`;
  return `/* Generated by tools/sync-brand.mjs. Do not edit: change brand/tokens/tokens.css or the site defaults. */\n\n`
    + `/* Site defaults: spec section 9.2 and Plan 4's motion tokens. */\n:root {\n${defaults}\n}\n\n${brand}`;
}

/** Custom properties a CSS file declares, name to value. */
export function declaredTokens(css) {
  const out = {};
  for (const match of css.matchAll(/(--[\w-]+)\s*:\s*([^;}]+)/g)) out[match[1]] = match[2].trim();
  return out;
}

/** Names the site relies on that the brand leaves undefined, and values that differ (case-insensitive). */
export function tokenDrift(brandCss) {
  const brand = declaredTokens(brandCss);
  const missing = Object.keys(SITE_TOKENS).filter((name) => !(name in brand));
  const different = Object.entries(SITE_TOKENS)
    .filter(([name, value]) => name in brand && brand[name].toLowerCase() !== value.toLowerCase())
    .map(([name, value]) => `${name}: site ${value}, brand ${brand[name]}`);
  return { missing, different };
}

const png = (svg, size, to) => execFileSync('rsvg-convert', ['-w', String(size), '-h', String(size), svg, '-o', to]);
const resize = (from, size, to) => execFileSync('sips', ['-z', String(size), String(size), from, '--out', to], { stdio: 'ignore' });

export async function syncBrand(repoRoot) {
  const report = [];
  const brandTokens = join(repoRoot, 'brand/tokens/tokens.css');
  const brandCss = existsSync(brandTokens) ? await readFile(brandTokens, 'utf8') : null;
  await writeFile(join(SITE_DIR, 'css/tokens.css'), renderTokens(brandCss));
  report.push(`css/tokens.css: ${brandCss === null ? 'site defaults' : 'site defaults + brand'}`);
  if (brandCss !== null) {
    const { missing, different } = tokenDrift(brandCss);
    if (missing.length) report.push(`  brand leaves these to the site: ${missing.join(', ')}`);
    for (const line of different) report.push(`  brand overrides ${line}`);
  }

  const out = join(SITE_DIR, 'assets/brand');
  await mkdir(out, { recursive: true });
  const pick = async (brandPath, fallbackPath, to, label) => {
    const from = existsSync(join(repoRoot, brandPath)) ? join(repoRoot, brandPath) : fallbackPath;
    await copyFile(from, join(out, to));
    report.push(`assets/brand/${to}: ${from === fallbackPath ? 'site fallback' : brandPath} (${label})`);
    return join(out, to);
  };
  await pick('brand/wordmark/pli-wordmark-ice.svg', join(FALLBACK, 'wordmark.svg'), 'wordmark.svg', 'nav and footer');
  const symbol = await pick('brand/symbol/pli-symbol.svg', join(FALLBACK, 'mark.svg'), 'symbol.svg', 'favicon');
  png(symbol, 32, join(out, 'favicon-32.png'));
  report.push('assets/brand/favicon-32.png: from symbol.svg');

  const icon = join(repoRoot, 'brand/icon-previews/default-1024.png');
  if (existsSync(icon)) {
    resize(icon, 256, join(out, 'icon-256.png'));
    resize(icon, 180, join(out, 'apple-touch-icon.png'));
    report.push('assets/brand/icon-256.png, apple-touch-icon.png: brand/icon-previews/default-1024.png');
  } else {
    png(join(FALLBACK, 'mark.svg'), 256, join(out, 'icon-256.png'));
    png(join(FALLBACK, 'mark.svg'), 180, join(out, 'apple-touch-icon.png'));
    report.push('assets/brand/icon-256.png, apple-touch-icon.png: site fallback');
  }

  const social = join(repoRoot, 'docs/brand/social-preview.png');
  if (existsSync(social)) {
    await copyFile(social, join(out, 'og.png'));
    report.push('assets/brand/og.png: docs/brand/social-preview.png');
  } else {
    report.push(`assets/brand/og.png: ${existsSync(join(out, 'og.png')) ? 'kept' : 'missing'} (made by node tools/export-og.mjs while the brand has none)`);
  }
  return report;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { values } = parseArgs({ options: { from: { type: 'string', default: resolve(SITE_DIR, '..') } } });
  for (const line of await syncBrand(resolve(values.from))) console.log(line);
}
